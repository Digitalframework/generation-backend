create table furniture_category
(
    id          bigint generated by default as identity primary key,
    room        varchar(32)  not null,
    name        varchar(64)  not null,
    slug        varchar(96)  not null,
    description varchar(512),
    created_at  timestamptz  not null,
    updated_at  timestamptz  not null,
    constraint uk_category_slug unique (slug),
    constraint uk_category_room_name unique (room, name)
);

create table furniture_image
(
    id           bigint generated by default as identity primary key,
    category_id  bigint        not null references furniture_category (id),
    file_name    varchar(255)  not null,
    content_type varchar(64)   not null,
    size_bytes   bigint        not null,
    width_px     integer       not null,
    height_px    integer       not null,
    sha256       varchar(64)   not null,
    width_cm     numeric(7, 2) not null,
    depth_cm     numeric(7, 2) not null,
    height_cm    numeric(7, 2) not null,
    style        varchar(64)   not null,
    data         bytea         not null,
    created_at   timestamptz   not null,
    updated_at   timestamptz   not null,
    constraint uk_image_sha256 unique (sha256)
);

create index idx_image_category on furniture_image (category_id);
create index idx_image_style on furniture_image (style);
